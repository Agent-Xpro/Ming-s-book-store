const params = new URLSearchParams(window.location.search);
const chapterNumber = Math.max(1, parseInt(params.get("chapter") || "1", 10));
const chapter = book.chapters[chapterNumber - 1];

function estimateMinutes(content) {
    const words = content.join(" ").trim().split(/\s+/).filter(Boolean).length;
    return Math.max(1, Math.ceil(words / 200));
}

function setText(id, value) {
    const element = document.getElementById(id);
    if (element) element.textContent = value;
}

function renderBookPage() {
    if (!document.getElementById("chapterList")) return;

    document.title = `${book.title} | Ink & Pages`;
    setText("coverGenre", book.genre.toUpperCase());
    setText("coverTitle", book.title);
    setText("bookGenre", book.genre.toUpperCase());
    setText("bookTitle", book.title);
    setText("bookAuthor", book.author);
    setText("bookDescription", book.description);
    setText("chapterCount", book.chapters.length);
    setText("readingTime", book.chapters.reduce((total, item) => total + estimateMinutes(item.content), 0));
    setText("bookYear", book.status);

    const start = document.getElementById("startReading");
    if (start) start.href = `chapter.html?id=${book.id}&chapter=1`;

    const list = document.getElementById("chapterList");
    list.innerHTML = book.chapters.map(item => `
        <a class="chapter" href="chapter.html?id=${book.id}&chapter=${item.number}">
            <span class="chapter-number">${String(item.number).padStart(2, "0")}</span>
            <span class="chapter-title">${item.title}</span>
            <span class="chapter-arrow">→</span>
        </a>
    `).join("");

    setText("chapterIntro", `${book.chapters.length} chapters · Begin with Chapter 1 or choose any chapter.`);
}

function renderReaderPage() {
    if (!document.getElementById("storyContent")) return;

    if (!chapter) {
        window.location.href = `book.html?id=${book.id}`;
        return;
    }

    document.title = `${chapter.title} — ${book.title} | Ink & Pages`;

    setText("readerBook", book.title.toUpperCase());
    setText("chapterNumber", String(chapter.number).padStart(2, "0"));
    setText("headingNumber", String(chapter.number).padStart(2, "0"));
    setText("chapterTitle", chapter.title);
    setText("readingTime", `${estimateMinutes(chapter.content)} min read`);
    setText("bookAuthor", book.author);

    const back = document.getElementById("backToBook");
    if (back) back.href = `book.html?id=${book.id}#chapters`;

    const listLink = document.getElementById("chapterListLink");
    if (listLink) listLink.href = `book.html?id=${book.id}#chapters`;

    const content = document.getElementById("storyContent");
    content.innerHTML = chapter.content.map((paragraph, index) =>
        index === 0 ? `<p class="drop-cap">${paragraph}</p>` : `<p>${paragraph}</p>`
    ).join("");

    const previous = document.getElementById("previousChapter");
    const previousTitle = document.getElementById("previousTitle");
    if (chapter.number > 1) {
        const item = book.chapters[chapter.number - 2];
        previous.href = `chapter.html?id=${book.id}&chapter=${item.number}`;
        previousTitle.textContent = item.title;
        previous.style.visibility = "visible";
    } else {
        previous.style.visibility = "hidden";
    }

    const next = document.getElementById("nextChapter");
    const nextTitle = document.getElementById("nextTitle");
    if (chapter.number < book.chapters.length) {
        const item = book.chapters[chapter.number];
        next.href = `chapter.html?id=${book.id}&chapter=${item.number}`;
        nextTitle.textContent = item.title;
        next.style.visibility = "visible";
    } else {
        next.style.visibility = "hidden";
    }
}

function updateProgress() {
    const bar = document.getElementById("progressBar");
    if (!bar) return;

    const height = document.documentElement.scrollHeight - window.innerHeight;
    const progress = height > 0 ? (window.scrollY / height) * 100 : 0;
    bar.style.width = `${Math.min(100, progress)}%`;
}

renderBookPage();
renderReaderPage();
window.addEventListener("scroll", updateProgress);
updateProgress();
